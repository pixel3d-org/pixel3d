//! A 5 x 7 bitmap font for labels drawn on rendered images (printable
//! ASCII; anything else draws as `?`). Glyphs are written as rows of `#`
//! (ink) and `.` (paper) and packed at compile time.

/// Glyph size in font pixels.
pub const GLYPH_W: usize = 5;
pub const GLYPH_H: usize = 7;

/// Packs one 5-wide row: the leftmost pixel is bit 4.
const fn row(s: &str) -> u8 {
    let b = s.as_bytes();
    let mut v = 0u8;
    let mut i = 0;
    while i < GLYPH_W {
        v <<= 1;
        if b[i] == b'#' {
            v |= 1;
        }
        i += 1;
    }
    v
}

macro_rules! glyph {
    ($($r:literal)*) => { [$(row($r)),*] };
}

