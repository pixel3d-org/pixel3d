/// The rows of a character's glyph.
pub fn glyph(c: char) -> [u8; GLYPH_H] {
    let i = c as u32;
    if (32..=126).contains(&i) { GLYPHS[(i - 32) as usize] } else { GLYPHS[(b'?' - 32) as usize] }
}

/// Whether font pixel (x, y) of a glyph is ink.
#[inline]
pub fn ink(g: &[u8; GLYPH_H], x: usize, y: usize) -> bool {
    x < GLYPH_W && y < GLYPH_H && (g[y] >> (GLYPH_W - 1 - x)) & 1 == 1
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyphs_pack_rows() {
        let a = glyph('A');
        assert_eq!(a[0], 0b01110);
        assert_eq!(a[3], 0b11111);
        assert!(ink(&a, 0, 1) && !ink(&a, 1, 1) && ink(&a, 4, 1));
        assert_eq!(glyph('\u{e9}'), glyph('?'));
        assert_eq!(glyph(' '), [0; GLYPH_H]);
        // Every printable glyph but space has ink.
        for c in 33u8..=126 {
            assert!(glyph(c as char).iter().any(|&r| r != 0), "{}", c as char);
        }
    }
}
